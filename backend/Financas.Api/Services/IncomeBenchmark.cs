    public static bool IsState(string? uf) => uf is not null && StateRegion.ContainsKey(uf);

    public static string AgeGroup(int age) => age switch
    {
        <= 24 => "18-24",
        <= 29 => "25-29",
        <= 39 => "30-39",
        <= 49 => "40-49",
        <= 59 => "50-59",
        _ => "60+",
    };

    /// <summary>Faixa por extenso, ex.: "25 a 29 anos".</summary>
    public static string AgeGroupLabel(string group) =>
        group.EndsWith('+') ? $"{group[..^1]} anos ou mais" : group.Replace("-", " a ") + " anos";

    /// <summary>Compara a renda com a de quem tem a mesma idade no país e na região. Sem renda: só as referências.</summary>
    public static Result Compare(int age, string? state, decimal? income)
    {
        var group = AgeGroup(Math.Max(age, 18));
        var region = state is not null && StateRegion.TryGetValue(state, out var r) ? r : "BR";
        var national = Rows[$"BR|{group}"];
        var regional = Rows[$"{region}|{group}"];
        return new Result(group, region, RegionNames[region], national.Mean, national.Median, regional.Mean,
            income is > 0 ? Percentile(national.Cuts, (double)income.Value) : null);
    }

    /// <summary>Porcentagem aproximada das pessoas da faixa que ganham menos que <paramref name="income"/>.</summary>
    public static int Percentile(int[] cuts, double income)
    {
        if (income < cuts[0]) return (int)Math.Round(5 * income / cuts[0]);
        var i = Array.FindLastIndex(cuts, c => c <= income);
        if (income == cuts[i])
        {
            // Muita gente ganha exatamente o mesmo valor (ex.: o salário mínimo): fica no meio desse grupo.
            var first = Array.IndexOf(cuts, cuts[i]);
            return (int)Math.Round((5.0 * first + 5.0 * (i + 1)) / 2);
        }
        if (i == cuts.Length - 1) return 97;
        return (int)Math.Round(5 * (i + 1) + 5 * (income - cuts[i]) / (cuts[i + 1] - cuts[i]));
    }
